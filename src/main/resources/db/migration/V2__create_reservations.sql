CREATE TABLE reservations (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id      BIGINT       NOT NULL,
    responsible  VARCHAR(100) NOT NULL,
    start_time   TIMESTAMP    NOT NULL,
    end_time     TIMESTAMP    NOT NULL,
    status       VARCHAR(20)  NOT NULL,
    created_at   TIMESTAMP    NOT NULL,
    cancelled_at TIMESTAMP,
    CONSTRAINT fk_reservations_room FOREIGN KEY (room_id) REFERENCES rooms (id),
    CONSTRAINT ck_reservations_time_range CHECK (end_time > start_time),
    CONSTRAINT ck_reservations_status CHECK (status IN ('ACTIVE', 'CANCELLED'))
);

-- Supports the overlap check (room + time range) and the room filter.
CREATE INDEX ix_reservations_room_time ON reservations (room_id, start_time, end_time);
-- Supports the date filter when no room is given.
CREATE INDEX ix_reservations_start_time ON reservations (start_time);
